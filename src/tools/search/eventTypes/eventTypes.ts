// The types are known without asking Unleash, so the query is matched here and costs Unleash nothing.
export const searchEventTypes = ({ query }: EventTypesQuery): EventTypes => {
  const text = query?.toLowerCase();
  return { kind: 'event_types', eventTypes: Object.keys(eventTypes).filter((type) => !text || type.includes(text)) };
};
